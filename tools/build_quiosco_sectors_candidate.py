#!/usr/bin/env python3
"""Package six AUTHORED complete Quiosco sectors as a non-active candidate.

Input: one independently painted pixel-exact panorama per sector.
No cropping/repeating, horizontal stretching, autogenerated buildings, or fake
Flutter evidence. The existing unique bandstand is copied losslessly.
Output: candidate zip for visual review; does NOT activate art in Flutter.
Usage:
 python3 tools/build_quiosco_sectors_candidate.py \
   --sector-dir /path/to/six/images --out /path/to/candidate.zip
Images: entrada.png, plaza_poniente.png, aproximacion.png,
quiosco_central.png, plaza_oriente.png, salida.png
Each has exactly (sector.end-sector.start) by 390 pixels.
"""
from __future__ import annotations
import argparse
import hashlib
import io
import json
import zipfile
from pathlib import Path
from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
PLAN = ROOT / "qa/quiosco_rc7_art_rebuild_plan.json"
OLD = ROOT / "assets/images/quiosco_rc7"
PREFIX = "assets/images/quiosco_rc7/"

def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def load_original_bandstand():
    manifest = json.loads((OLD / "manifest.json").read_text(encoding="utf-8"))
    raw = (OLD / "quiosco_unico.webp").read_bytes()
    if digest(raw) != manifest["landmark"]["sha256"]:
        raise ValueError("Existing unique Quiosco SHA mismatch")
    return manifest, raw

def run(sector_dir: Path, output: Path) -> None:
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    old_manifest, original_bandstand = load_original_bandstand()
    sectors = plan["sectors"]
    assert plan["world_width"] == 37440
    assert plan["tile_width"] == 960 and plan["tile_height"] == 390
    assert old_manifest["landmark"]["count"] == 1
    assert old_manifest["landmark"]["world_x"] == plan["landmark"]["world_x"]
    assert old_manifest["landmark"]["width"] == plan["landmark"]["width"]

    source_records = []
    pieces = []
    for sector in sectors:
        name = sector["id"] + ".png"
        source = sector_dir / name
        if not source.is_file():
            raise FileNotFoundError(f"Missing original authored sector: {source}")
        with Image.open(source) as picture:
            expected = (sector["end"] - sector["start"], plan["tile_height"])
            if picture.size != expected:
                raise ValueError(f"{name} {picture.size} != {expected}; do not resize or repeat")
            if picture.mode not in ("RGB", "RGBA"):
                raise ValueError(f"{name} must be RGB(A)")
            rgba = picture.convert("RGBA")
            if rgba.getextrema()[3][0] < 255:
                raise ValueError(f"{name} has transparent pixels; complete backdrop required")
            pieces.append(rgba.copy())
        source_records.append({"part": "facade_authored_sector",
                               "source": name, "world_start": sector["start"],
                               "width": expected[0], "sha256": digest(source.read_bytes())})

    hashes = [x["sha256"] for x in source_records]
    if len(set(hashes)) != len(hashes):
        raise ValueError("Identical source panoramas used twice")
    # Reject obviously identical adjacent border columns; inspect boundaries visually
    # regardless of this safeguard. Art review remains REQUIRED.
    world = Image.new("RGBA", (plan["world_width"], plan["tile_height"]))
    for sector, im in zip(sectors, pieces):
        world.paste(im, (sector["start"], 0))
    # Extract exact pixels without re-scaling.
    tiles = []
    output.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(output, "w", zipfile.ZIP_DEFLATED) as archive:
        for idx in range(plan["world_width"] // plan["tile_width"]):
            start = idx * plan["tile_width"]
            panel = world.crop((start, 0, start + plan["tile_width"], plan["tile_height"]))
            buffer = io.BytesIO()
            panel.save(buffer, "WEBP", lossless=True, method=6)
            raw = buffer.getvalue()
            filename = f"quiosco_{idx:02d}.webp"
            archive.writestr(PREFIX + filename, raw)
            tiles.append({"tile": idx, "filename": filename,
                          "world_start": start, "sha256": digest(raw)})
        archive.writestr(PREFIX + "quiosco_unico.webp", original_bandstand)
        manifest = {"tile_count": len(tiles), "tile_width": 960,
                    "tile_height": 390, "world_width": 37440,
                    "landmark": old_manifest["landmark"], "tiles": tiles,
                    "source_details": source_records,
                    "art_status": "CANDIDATE_NOT_VISUALLY_APPROVED",
                    "construction": "six unique full-width authored panoramas, no repeats"}
        archive.writestr(PREFIX + "manifest.json",
                         json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    print("Candidate prepared:", output)
    print("SHA256:", digest(output.read_bytes()))
    print("NOT INTEGRATED / NOT STAGEPAINTER / NOT APPROVED")

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--sector-dir", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    run(args.sector_dir, args.out)
