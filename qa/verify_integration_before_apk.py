#!/usr/bin/env python3
"""Physical pre-APK integration gate for The Wolf Company, PR #5.

Run AFTER generating every resource and BEFORE flutter build apk:
  python3 qa/verify_integration_before_apk.py --strict

Verifies real generated bytes, source/manifest consistency, intact classic
poses, art-path presence and manual-only GitHub workflow. It cannot confer
artistic acceptance or replace authentic StagePainter/Android inspection.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/images'
OUT = ROOT / 'qa/PREAPK_INTEGRATION_G.json'


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def png_info(path: Path):
    """Use real PNG header; leave complete decode checks to Pillow QA."""
    if not path.is_file():
        return None
    with path.open('rb') as f:
        header = f.read(24)
    if len(header) != 24 or header[:8] != b'\x89PNG\r\n\x1a\n':
        return None
    w, h = struct.unpack('>II', header[16:24])
    return (w, h) if w > 0 and h > 0 else None


def audit():
    failures = []
    evidence = {}

    def check(key, condition, reason):
        if not condition:
            failures.append({'key': key, 'reason': reason})

    title = ASSETS / 'title_wide_20x9.png'
    logo = ASSETS / 'twc_title_mark_clean.png'
    check('A.title', png_info(title) is not None,
          'Panorámica real 20:9 ausente/inválida (NO generar relleno)')
    check('A.logo', png_info(logo) is not None,
          'Sello TWC transparente ausente/inválido')
    evidence['A'] = {'title_sha256': digest(title) if png_info(title) else None}

    school_dir = ASSETS / 'interiors_parallax/school'
    school = [school_dir / f'z{z}_panel_{n}.png'
              for z in range(3) for n in range(9)]
    good_school = [p for p in school if png_info(p) == (880, 278)]
    check('B.school', len(good_school) == 27,
          f'Paneles escolares válidos {len(good_school)}/27')
    evidence['B'] = {'valid_panels': len(good_school),
                     'sha256': {p.name: digest(p) for p in good_school}}

    dance_dir = ASSETS / 'interiors_parallax/dance'
    dance_manifest = ROOT / 'qa/interiors_twc_lab/DANCE_PANEL_GENERATION.json'
    dance_paths = [dance_dir / f'z{z}_panel_{n}.png'
                   for z in range(3) for n in range(3)]
    correct_dance = 0
    matched_dance = 0
    entries = []
    if dance_manifest.is_file():
        try:
            entries = json.loads(dance_manifest.read_text())['panels']
        except (ValueError, KeyError, TypeError):
            failures.append({'key': 'C.manifest', 'reason': 'Manifiesto danza ilegible'})
    else:
        failures.append({'key': 'C.manifest',
                         'reason': 'Falta manifiesto regenerado en este checkout'})
    by_id = {(x.get('zone'), x.get('variant')): x
             for x in entries if isinstance(x, dict)}
    for z in range(3):
        for n in range(3):
            path = dance_dir / f'z{z}_panel_{n}.png'
            if png_info(path) == (880, 286):
                correct_dance += 1
                if by_id.get((z, n), {}).get('sha256') == digest(path):
                    matched_dance += 1
    check('C.dance', correct_dance == 9 and matched_dance == 9,
          f'Danza 9 PNG 880x286 y hashes de manifiesto: '
          f'{correct_dance}/9 válidos, {matched_dance}/9 SHA iguales')
    evidence['C'] = {'valid_panels': correct_dance,
                     'manifest_sha_matched': matched_dance}

    football_dir = ASSETS / 'chapter45/football_parallax'
    football_manifest = football_dir / 'MANIFEST.json'
    near = [football_dir / f'near_world_tiles/near_{n}.png'
            for n in range(6)]
    good_near = [p for p in near if png_info(p) == (1100, 386)]
    check('D.football', len(good_near) == 6,
          f'Cercado fútbol válido {len(good_near)}/6')
    if football_manifest.is_file():
        try:
            fm = json.loads(football_manifest.read_text())
            seq = fm['near']['source_sequence']
            check('D.sources', len(seq) == 8 and
                  set(seq) == {'football_arrival', 'football_drills',
                               'football_stands'},
                  'Fútbol debe combinar las tres ilustraciones genuinas')
            for name, expected in fm['source_sha256'].items():
                source = ASSETS / f'chapter45/{name}.png'
                check(f'D.source.{name}', source.is_file() and
                      digest(source) == expected,
                      f'Fuente de fútbol modificada o ausente: {name}')
        except (KeyError, TypeError, ValueError):
            failures.append({'key': 'D.manifest',
                             'reason': 'Manifiesto de fútbol obsoleto/inválido'})
    else:
        failures.append({'key': 'D.manifest',
                         'reason': 'Falta manifiesto de fútbol regenerado'})
    evidence['D'] = {'valid_near_panels': len(good_near)}

    enemy_dir = ASSETS / 'enemies_new'
    kinds = ('robot', 'supporter', 'tourist', 'navarre_king',
             'estafeta_bull', 'sanfermin_runner')
    enemy_files = {name: enemy_dir / f'{name}_atlas.png' for name in kinds}
    missing = [name for name, path in enemy_files.items()
               if png_info(path) is None]
    check('E.atlases', not missing,
          f'Atlases nuevos ausentes/ilegibles: {missing}')
    evidence['E'] = {
        'present': [name for name in kinds if name not in missing],
        'note': 'Presencia NO acredita calidad, animación ni aprobación'
    }

    classic = ASSETS / 'enemies'
    classic_counts = {'breakdancer': 6, 'bully': 5,
                      'referee': 6, 'rival': 6}
    missing_classic = [f'{name}_{n}' for name, count in classic_counts.items()
                       for n in range(count)
                       if png_info(classic / f'{name}_{n}.png') is None]
    check('F.classics', not missing_classic,
          f'Pose clásica ausente/ilegible: {missing_classic}')
    bounds = ROOT / 'lib/sprite_bounds.g.dart'
    check('F.rival_5_bound', bounds.is_file() and
          "'rival_5':" in bounds.read_text(encoding='utf-8'),
          'El rival usa su sexta pose pero faltan límites alfa generados')
    evidence['F'] = {'valid_frames': 23 - len(missing_classic),
                     'rival_final_frame': 'rival_5.png'}

    main = (ROOT / 'lib/main.dart').read_text(encoding='utf-8')
    check('G.loader', "v=='referee' || v=='breakdancer' || v=='rival'" in main,
          'El cargador Dart debe cargar el sexto fotograma rival')
    workflow = (ROOT / '.github/workflows/build.yml').read_text(encoding='utf-8')
    head = workflow.split('jobs:', 1)[0]
    check('G.no_auto_actions', bool(re.search(
          r'(?m)^\s+workflow_dispatch\s*:', head)) and
          not re.search(r'(?m)^\s+(push|pull_request|schedule|workflow_run)\s*:',
                        head),
          'Se detecta posible disparador automático de GitHub Actions')
    for name in ('build_interiors_parallax_twc.py',
                 'build_dance_panels_twc.py',
                 'build_football_parallax_twc.py',
                 'generate_new_enemy_sprites.py',
                 'generate_navarre_king.py',
                 'generate_estafeta_enemies.py',
                 'refine_four_classic_enemies.py',
                 'export_sprite_bounds.py'):
        check('G.generator.' + name, ('python3 tools/' + name) in workflow,
              'Generador no integrado al workflow: ' + name)
    check('G.dance_shas',
          workflow.count('python3 -m unittest qa.test_dance_proportions') == 2,
          'El APK y las capturas deben comprobar los mismos nueve paneles')
    evidence['G'] = {
        'workflow_manual_only': bool(re.search(
            r'(?m)^\s+workflow_dispatch\s*:', head)),
        'note': 'NO se ha ejecutado Flutter ni Android'
    }
    return failures, evidence


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--strict', action='store_true')
    args = parser.parse_args()
    problems, evidence = audit()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    result = {
        'verified_by': 'Python filesystem/header/hash checks',
        'art_approved': False,
        'flutter_tested': False,
        'android_tested': False,
        'technical_failures': problems,
        'evidence': evidence
    }
    OUT.write_text(json.dumps(result, indent=2, ensure_ascii=False) + '\n',
                   encoding='utf-8')
    for issue in problems:
        print('BLOQUEADO', issue['key'] + ':', issue['reason'])
    print('G: %s; reporte %s' %
          ('OK TECNICO (NO ARTE)' if not problems else
           f'{len(problems)} bloqueos técnicos', OUT))
    return 2 if problems and args.strict else 0


if __name__ == '__main__':
    sys.exit(main())
